"""Регулярные выражения для кодов и полей РПД.

Работают по тексту, где тире уже нормализованы к «-» (см. md_utils.clean_text).
Коды ПКП хранятся как есть: «ПКП-ППК-ОС3» и «ПКП-16-ППК-ОС3» — разные строки.
"""

import re

_PREFIX = r"(?:ПКП|ПКА|УНК|УКБ|УК|ОПК)"
_NOT_WORD_BEFORE = r"(?<![0-9A-Za-zА-Яа-яЁё])"

# УК-1, ОПК-2, ПКП-ППК-ОС3, ПКП-УНК-01, ПКП-16-ППК-ОС3
COMPETENCE_CODE = rf"{_NOT_WORD_BEFORE}{_PREFIX}(?:-[0-9А-ЯЁ]+)+"
# УК-1.2, ПКП-ППК-ОС3.1, ПКП-УНК-03.01
INDICATOR_CODE = rf"{COMPETENCE_CODE}\.[0-9]+"
# ПКП-ППК-ОС3.1. З-1 (З — знает, У — умеет, В — владеет; встречается опечатка «3-1»)
OUTCOME_CODE = rf"{INDICATOR_CODE}\.?\s*[ЗУВ3]-[0-9]+"

COMPETENCE_RE = re.compile(COMPETENCE_CODE)
INDICATOR_RE = re.compile(INDICATOR_CODE)
OUTCOME_RE = re.compile(OUTCOME_CODE)
# Код компетенции в начале ячейки, дальше — необязательное название
COMPETENCE_CELL_RE = re.compile(rf"\s*({COMPETENCE_CODE})[.:,;]?(?:\s+(.*))?$", re.S)
# Название, затем код в скобках: «способен проектировать ... (ПКП-МО-1)»
NAME_THEN_CODE_RE = re.compile(rf"^(.*?)\s*\(\s*({COMPETENCE_CODE})\s*\)\.?$", re.S)
# Код в скобках: «(ПКП-УНК-03.01. З-1)»
SUFFIX_OUTCOME_RE = re.compile(rf"\(\s*({OUTCOME_CODE})\s*\)")

LEVEL_RE = re.compile(r"\((Базовый|Средний|Продвинутый)\)\s*\.?\s*$", re.I)
# «знает:», «знать:», а также «знать» без двоеточия перед маркером списка
KIND_HEADING_RE = re.compile(
    r"(?<![А-Яа-яЁё])(знает|знать|умеет|уметь|владеет|владеть)\s*(?::|(?=\s*[*•]))", re.I
)
KIND_CANONICAL = {
    "знает": "знает",
    "знать": "знает",
    "умеет": "умеет",
    "уметь": "умеет",
    "владеет": "владеет",
    "владеть": "владеет",
}
KIND_WORD_RE = re.compile(r"^(знает|знать|умеет|уметь|владеет|владеть)\b", re.I)
# Граница пунктов «...; Уметь ...» / «... . Умеет ...» внутри одной ячейки без маркеров
KIND_SPLIT_RE = re.compile(r"(?<=[;.])\s+(?=(?:знает|знать|умеет|уметь|владеет|владеть)\b)", re.I)
LANGUAGE_LINE_RE = re.compile(r"^Язык\(?и?\)?\s+обучения", re.I)
BULLET_RE = re.compile(r"(?:^|\s)[*•]\s*")

CREDITS_RE = re.compile(r"Трудо[её]мкость[^:\n]*:\s*([0-9]+(?:[.,][0-9]+)?)")
REG_NUMBER_RE = re.compile(r"Регистрационный номер[^:\n]*:\s*([0-9A-Za-zА-Яа-я\-/]+)")
SEMESTER_ROW_RE = re.compile(r"^Семестр\s+(\d+)", re.I)

# Виды промежуточной аттестации; всё остальное в строке семестра — текущий контроль
INTERMEDIATE_RE = re.compile(
    r"^(?:дифференцированный\s+)?(?:экзамен|зач[её]т)(?:\s+с\s+оценкой)?\b", re.I
)

KIND_BY_LETTER = {"З": "знает", "3": "знает", "У": "умеет", "В": "владеет"}

# Вид аттестации внутри ячейки: «экзамен», «зачёт», «зачет с оценкой», «дифференцированный зачёт»
ATTESTATION_KIND_RE = re.compile(
    r"(?:дифференцированный\s+)?(?:экзамен|зач[её]т(?:\s+с\s+оценкой)?)", re.I
)
